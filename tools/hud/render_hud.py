"""Renders the HUD art into Data/F4SE/Plugins/fo4pool/hud and writes src/HudAtlas.h.

  python tools/hud/render_hud.py

Panels and balls come from panels.html (rendered with Playwright at 3x, so they stay sharp up to 4K). The two
fonts (Chakra Petch Bold, Share Tech Mono; SIL Open Font License) are baked into glyph atlases with a matching
glow atlas, so the DLL can draw glowing terminal text at any size without touching the shared ImGui font setup.
"""
import json
import pathlib
from PIL import Image, ImageDraw, ImageFilter, ImageFont
from playwright.sync_api import sync_playwright

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
OUT = ROOT / "dist/Data/F4SE/Plugins/fo4pool/hud"
SCALE = 3  # pixels per design unit in the PNGs

PANELS = ["score", "tag", "banner_red", "banner_green", "small", "call", "meter", "glass"] + [f"ball{n}" for n in range(16)]


def render_panels():
    info = {}
    with sync_playwright() as p:
        browser = p.chromium.launch()
        page = browser.new_page(device_scale_factor=SCALE, viewport={"width": 1400, "height": 9000})
        page.goto((HERE / "panels.html").as_uri())
        page.wait_for_timeout(300)
        for name in PANELS:
            el = page.locator(f"#{name}")
            box = el.bounding_box()
            pad = page.evaluate(f"parseFloat(getComputedStyle(document.getElementById('{name}')).paddingLeft)")
            el.screenshot(path=str(OUT / f"{name}.png"), omit_background=True)
            info[name] = {"w": box["width"], "h": box["height"], "pad": pad}
        browser.close()
    return info


CHARS = "".join(chr(c) for c in range(32, 127)) + "·–"


def bake_font(ttf, px, name, glow_radius):
    font = ImageFont.truetype(str(HERE / ttf), px)
    ascent, descent = font.getmetrics()
    pad = glow_radius * 3
    cells = []
    for ch in CHARS:
        l, t, r, b = font.getbbox(ch)
        w, h = max(1, r - l), max(1, b - t)
        cells.append((ch, l, t, w, h, font.getlength(ch)))
    # shelf-pack into a 1024-wide atlas
    width, x, y, row = 1024, 0, 0, 0
    places = []
    for ch, l, t, w, h, adv in cells:
        cw, chh = w + pad * 2, h + pad * 2
        if x + cw > width:
            x, y, row = 0, y + row, 0
        places.append((x, y))
        x += cw
        row = max(row, chh)
    height = 1
    while height < y + row:
        height *= 2
    sharp = Image.new("L", (width, height), 0)
    for (ch, l, t, w, h, adv), (px0, py0) in zip(cells, places):
        ImageDraw.Draw(sharp).text((px0 + pad - l, py0 + pad - t), ch, font=font, fill=255)
    glow = sharp.filter(ImageFilter.GaussianBlur(glow_radius))
    glow = glow.point(lambda v: min(255, int(v * 2.2)))
    for img, suffix in ((sharp, ""), (glow, "_glow")):
        rgba = Image.new("RGBA", img.size, (255, 255, 255, 0))
        rgba.putalpha(img)
        rgba.save(OUT / f"font_{name}{suffix}.png")
    glyphs = []
    for (ch, l, t, w, h, adv), (px0, py0) in zip(cells, places):
        glyphs.append((ord(ch), px0, py0, w + pad * 2, h + pad * 2, l - pad, t - pad, adv))
    return {"size": px, "ascent": ascent, "w": width, "h": height, "glyphs": glyphs}


def write_header(panels, fonts):
    lines = [
        "#pragma once",
        "// Generated by tools/hud/render_hud.py: where everything is in the HUD's PNGs. Don't edit by hand.",
        "",
        "namespace fp::HudAtlas",
        "{",
        f"\tconstexpr float kPanelScale = {SCALE}.0f;  // PNG pixels per design unit",
        "",
        "\tstruct Panel { const char* file; float w, h, pad; };  // design units; w/h include the padding",
        "\tstruct Glyph { std::uint32_t code; float x, y, w, h, xoff, yoff, advance; };  // atlas pixels",
        "\tstruct Font { const char* file; const char* glowFile; float size, ascent, atlasW, atlasH; const Glyph* glyphs; int count; };",
        "",
    ]
    for name in PANELS:
        p = panels[name]
        lines.append(f"\tinline constexpr Panel k_{name}{{ \"{name}.png\", {p['w']:.2f}f, {p['h']:.2f}f, {p['pad']:.2f}f }};")
    lines.append("")
    for name, f in fonts.items():
        lines.append(f"\tinline constexpr Glyph k_{name}Glyphs[] = {{")
        for g in f["glyphs"]:
            lines.append(f"\t\t{{ {g[0]}, {g[1]}, {g[2]}, {g[3]}, {g[4]}, {g[5]}, {g[6]}, {g[7]:.3f}f }},")
        lines.append("\t};")
        lines.append(
            f"\tinline constexpr Font k_{name}{{ \"font_{name}.png\", \"font_{name}_glow.png\", {f['size']}.0f, {f['ascent']}.0f, "
            f"{f['w']}.0f, {f['h']}.0f, k_{name}Glyphs, {len(f['glyphs'])} }};")
        lines.append("")
    lines.append("}")
    (ROOT / "src/HudAtlas.h").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    panels = render_panels()
    fonts = {"title": bake_font("ChakraPetch-Bold.ttf", 96, "title", 6), "mono": bake_font("ShareTechMono-Regular.ttf", 56, "mono", 4)}
    write_header(panels, fonts)
    print("panels:", json.dumps(panels))
    print("fonts:", {k: (v["w"], v["h"], len(v["glyphs"])) for k, v in fonts.items()})
